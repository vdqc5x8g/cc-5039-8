// Builds the sample offline packages used by the docs, the checker, and the
// browser loader. Produces one valid package plus one package per damaged
// variant, each in its own directory under packages/.
//
//   node tools/build-samples.js
//
// Requires origin-data/ (run `npm run build:media` first). Rebuilding the media
// library removes packages/ (see build-media.js), so this is the way to
// regenerate them — never a hand-edited copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildPackage, damagePackage, VARIANTS } from './build-package.js';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT = path.join(ROOT, 'packages');

export const SAMPLES = [
  { name: 'course-a-360p', courseId: 'course-a', selection: { quality: '360p', audio: 'en', subs: ['en', 'zh'] } },
  { name: 'course-b-360p', courseId: 'course-b', selection: { quality: '360p', audio: 'zh', subs: ['zh'] } },
];

const VARIANTS_OF = 'course-a-360p';

export function buildSamples() {
  if (!fs.existsSync(path.join(ROOT, 'origin-data', 'catalog.json'))) {
    throw new Error('缺少 origin-data/，请先运行 npm run build:media');
  }
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  const built = [];
  for (const sample of SAMPLES) {
    const dir = path.join(OUT, sample.name);
    buildPackage({ courseId: sample.courseId, selection: sample.selection, outDir: dir });
    built.push({ name: sample.name, dir, variant: null });
  }

  for (const variant of VARIANTS) {
    const name = `${VARIANTS_OF}--${variant}`;
    const dir = path.join(OUT, name);
    // Start from a fresh good copy, then damage exactly that copy.
    buildPackage({ courseId: 'course-a', selection: SAMPLES[0].selection, outDir: dir });
    damagePackage(dir, variant);
    built.push({ name, dir, variant });
  }

  const readme = [
    'These packages are generated by `npm run packages:build`.',
    'Do not edit them by hand; change tools/build-samples.js and regenerate.',
    'Valid samples: course-a-360p, course-b-360p.',
    `Damaged variants (all must fail the contract check): ${VARIANTS.join(', ')}.`,
  ].join('\n');
  fs.writeFileSync(path.join(OUT, 'README.txt'), `${readme}\n`);
  return built;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  const built = buildSamples();
  for (const item of built) {
    console.log(`${item.variant ? 'variant' : 'package'}  ${item.name}`);
  }
  console.log(`\n${built.length} 个样例包生成于 ${path.relative(ROOT, OUT)}/`);
}
